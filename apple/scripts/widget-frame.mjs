#!/usr/bin/env node
// Writes the widget frame's document pieces into Swift, so the app builds the same page the web page does and the two cannot drift.
//   node apple/scripts/widget-frame.mjs            writes Widgets/WidgetPage.generated.swift
//   node apple/scripts/widget-frame.mjs --check    exits 1 when that file is stale
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ACTIVE_MS, frameBoot, frameDoc, CSP, HEIGHT_MAX, HEIGHT_MIN, LINK_MAX, PROMPT_MAX } from '../../public/ui/widget-frame.js';
import { CARD_CLASS, hostCss } from '../../public/ui/widget-theme.js';

export const TARGET = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'GhostShellKit', 'Sources', 'GhostShellKit', 'Widgets', 'WidgetPage.generated.swift');

// A multi-line raw string literal. It takes enough # that no quote or backslash in the text is followed by that many of them.
export function rawLiteral(text) {
  let n = 1;
  while (text.includes(`"${'#'.repeat(n)}`) || text.includes(`\\${'#'.repeat(n)}`)) n++;
  const hashes = '#'.repeat(n);
  return `${hashes}"""\n${text}\n"""${hashes}`;
}

export function generate() {
  const goldens = {
    goldenDarkPlain: frameDoc('<p>golden</p>', { mode: 'dark', card: false }),
    goldenLightCard: frameDoc('<svg viewBox="0 0 10 5"></svg>', { mode: 'light', card: true }),
  };
  const text = (name, value) => `    static let ${name} = ${rawLiteral(value)}`;
  return [
    '// Generated by apple/scripts/widget-frame.mjs from public/ui/widget-frame.js and widget-theme.js. Do not edit.',
    '// Rerun `node apple/scripts/widget-frame.mjs` after either changes. test/apple-widget-frame.test.mjs fails while this file is stale.',
    '',
    'enum WidgetPage {',
    text('csp', CSP),
    text('hostCss', hostCss()),
    text('frameBoot', String(frameBoot)),
    `    static let cardClass = "${CARD_CLASS}"`,
    `    static let heightMin = ${HEIGHT_MIN}`,
    `    static let heightMax = ${HEIGHT_MAX}`,
    `    static let activeMs = ${ACTIVE_MS}`,
    `    static let promptMax = ${PROMPT_MAX}`,
    `    static let linkMax = ${LINK_MAX}`,
    text('goldenDarkPlain', goldens.goldenDarkPlain),
    text('goldenLightCard', goldens.goldenLightCard),
    '}',
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const fresh = generate();
  if (process.argv.includes('--check')) {
    const held = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : null;
    if (held !== fresh) {
      console.error('WidgetPage.generated.swift is stale. Run: node apple/scripts/widget-frame.mjs');
      process.exit(1);
    }
    console.log('WidgetPage.generated.swift is current.');
  } else {
    fs.mkdirSync(path.dirname(TARGET), { recursive: true });
    fs.writeFileSync(TARGET, fresh);
    console.log(`Wrote ${path.relative(process.cwd(), TARGET)} (${fresh.length} characters).`);
  }
}
