// What Claude is doing in a chat Capcom does not run, read from the transcript the other app saves. Desktop and a terminal send
// Capcom no stream, so the open turn is rebuilt from the saved entries: when it began, the tool calls still waiting for a result
// and the output tokens of the replies finished so far. Nothing is saved. The result holds what the page reads of a work
// snapshot, in the same keys: the tools, the tokens, how long the turn has run and when it began.
import fs from 'node:fs';
import path from 'node:path';
import { completeEnd, readRange, textOf } from './transcripts.mjs';

const NEWLINE = 0x0a;
const CHUNK = 1024 * 1024;
const INTERRUPTED = '[Request interrupted by user';
const LOCAL_OUTPUT = /^<local-command-(stdout|stderr)>/;
// A command the owner ran with ! in a terminal, and the caveat the CLI writes before the output of a local command. Claude never
// replies to any of them, so they neither open a turn nor end one.
const SHELL = /^<bash-(input|stdout|stderr)>/;
const CAVEAT = /^(<local-command-caveat>|caveat: the messages below were generated by the user while running local commands)/i;
// Capcom's own headless CLI. Its turns already show from the CLI's stream, and one cut off by a restart must not look alive.
const OWN = 'sdk-cli';

// How long a transcript can stay still before its turn is no longer live. The session list leaves an older one unread unless its chat is open.
export const STALE_MS = 10 * 60_000;

// What an entry that ends the turn does. It carries nothing, so every such entry is this one value.
const END = { end: true };

// What one saved entry does to the open turn: END, null when it changes nothing, or a part to add. An assistant message is saved
// once per content block and each entry repeats the message's final usage and stop reason. So a reply that ends the turn ends it
// on every one of its entries, and tokens are kept per message id instead of added up per entry. A part `opens` when it can be
// the start of a turn: a prompt (a user entry that answers no tool call) or a message queued while Claude works.
function classify(e) {
  if (!e || e.isSidechain === true) return null;
  if (e.type === 'system') return e.subtype === 'turn_duration' ? END : null;
  const at = typeof e.timestamp === 'string' ? Date.parse(e.timestamp) : NaN;
  const part = { at: Number.isNaN(at) ? null : at, by: typeof e.entrypoint === 'string' ? e.entrypoint : '', opens: false, tools: [], done: [], spent: null };
  if (e.type === 'attachment') {
    if (e.attachment?.type !== 'queued_command') return null;
    part.opens = true;
    return part;
  }
  const message = e.message;
  const blocks = Array.isArray(message?.content) ? message.content : [];
  if (e.type === 'assistant') {
    const why = message?.stop_reason;
    if (typeof why === 'string' && why && why !== 'tool_use' && why !== 'pause_turn') return END;
    for (const b of blocks) {
      if (b?.type === 'tool_use') part.tools.push({ id: b.id, name: typeof b.name === 'string' ? b.name : '' });
    }
    if (Number.isFinite(message?.usage?.output_tokens)) part.spent = [message.id ?? '', message.usage.output_tokens];
    return part;
  }
  if (e.type !== 'user') return null;
  const said = textOf(message?.content).trim();
  if (said.startsWith(INTERRUPTED) || LOCAL_OUTPUT.test(said)) return END;
  if (e.isCompactSummary || SHELL.test(said) || CAVEAT.test(said)) return null;
  let answers = false;
  for (const b of blocks) {
    if (b?.type !== 'tool_result') continue;
    answers = true;
    part.done.push(b.tool_use_id);
  }
  part.opens = !answers;
  return part;
}

// A prompt cannot belong to the open turn when another app wrote it, or when it comes more than `staleMs` after the turn's newest
// entry. The app that wrote the turn quit before it ended, so the turn is dead and the prompt begins the next one.
const apart = (turn, part, staleMs) => part.by !== turn.by || (part.at !== null && turn.last !== null && part.at - turn.last > staleMs);

// A turn takes its app from the entry that opened it. Its start is the first readable time, so a first entry with no readable
// time leaves the start to the next entry that has one. `last` is the newest readable time, which the next prompt is measured from.
function apply(state, part, staleMs) {
  if (part === END) { state.turn = null; return; }
  if (state.turn && part.opens && apart(state.turn, part, staleMs)) state.turn = null;
  const turn = (state.turn ??= { start: null, last: null, by: part.by, tools: new Map(), spent: new Map() });
  turn.start ??= part.at;
  if (part.at !== null) turn.last = Math.max(turn.last ?? part.at, part.at);
  for (const tool of part.tools) turn.tools.set(tool.id, tool);
  for (const id of part.done) turn.tools.delete(id);
  if (part.spent) turn.spent.set(...part.spent);
}

// The newest write among the files in a folder, or -Infinity when there is none.
function newest(dir) {
  let at = -Infinity;
  try {
    for (const name of fs.readdirSync(dir)) {
      try { at = Math.max(at, fs.statSync(path.join(dir, name)).mtimeMs); } catch {}
    }
  } catch {}
  return at;
}

// The lines of file[floor, end) from the newest to the oldest, read a chunk at a time from the end. `end` is just after a newline.
// The oldest piece only counts as a line when the window begins on the first byte of one, which is the start of the file or the
// byte after a newline. Otherwise it was cut part way.
export function* linesBack(file, end, floor, chunk) {
  let at = end;
  let rest = Buffer.alloc(0);
  while (at > floor) {
    const from = Math.max(floor, at - chunk);
    rest = Buffer.concat([readRange(file, from, at), rest]);
    at = from;
    let stop = rest.length - 1;
    for (let prev; stop > 0 && (prev = rest.lastIndexOf(NEWLINE, stop - 1)) >= 0; stop = prev) yield rest.subarray(prev + 1, stop);
    rest = rest.subarray(0, stop + 1);
  }
  if (rest.length > 1 && (at === 0 || readRange(file, at - 1, at)[0] === NEWLINE)) yield rest.subarray(0, rest.length - 1);
}

function parse(line) {
  try { return classify(JSON.parse(line.toString('utf8'))); } catch { return null; }
}

// The server asks for every open viewer every 1.5 s, so a file is parsed once: each file keeps how far it was read and the turn
// found so far, and a later read adds only the lines written since.
export function createOutside({ now = Date.now, staleMs = STALE_MS, lookBackBytes = 16 * 1024 * 1024, subagentsEveryMs = 15_000, keep = 64 } = {}) {
  const seen = new Map();
  const chunk = Math.min(CHUNK, lookBackBytes);
  const quiet = at => now() - at >= staleMs;

  // Reads re-add the file, so the first in the map is the one read longest ago.
  function remember(file) {
    const state = seen.get(file) ?? { offset: -1, turn: null, looked: -Infinity, agents: -Infinity };
    seen.delete(file);
    seen.set(file, state);
    while (seen.size > keep) seen.delete(seen.keys().next().value);
    return state;
  }

  // The agents a chat starts write their own files, so a long agent run leaves the main file still for minutes. Their folder is
  // looked at only once the main file has gone quiet, and then not on every read.
  function awake(t, state, mtime) {
    if (!quiet(mtime)) return true;
    const at = now();
    if (at - state.looked >= subagentsEveryMs) {
      state.looked = at;
      state.agents = newest(path.join(path.dirname(t.file), t.id, 'subagents'));
    }
    return !quiet(state.agents);
  }

  // Reads back from the last finished line until an entry that ends a turn, or as far as lookBackBytes. A turn longer than that
  // starts at the oldest entry in the window, which undercounts it.
  function rebuild(t, state) {
    const end = completeEnd(t);
    const parts = [];
    for (const line of linesBack(t.file, end, Math.max(0, end - lookBackBytes), chunk)) {
      const part = parse(line);
      if (part === END) break;
      if (part) parts.push(part);
    }
    state.turn = null;
    state.offset = end;
    for (const part of parts.reverse()) apply(state, part, staleMs);
  }

  // Only finished lines, so a line still being written waits for the read after it.
  function forward(t, state, size) {
    const buf = readRange(t.file, state.offset, size);
    const last = buf.lastIndexOf(NEWLINE);
    if (last < 0) return;
    for (let from = 0, nl; from <= last; from = nl + 1) {
      nl = buf.indexOf(NEWLINE, from);
      const part = parse(buf.subarray(from, nl));
      if (part) apply(state, part, staleMs);
    }
    state.offset += last + 1;
  }

  function read(t) {
    if (!t?.file) return null;
    let st;
    try { st = fs.statSync(t.file); } catch { seen.delete(t.file); return null; }
    const state = remember(t.file);
    // A chat that has gone quiet is not read at all, so the many old ones cost a stat each.
    if (!awake(t, state, st.mtimeMs)) return null;
    try {
      // Never read, rewritten smaller, or grown by more than a rebuild would read anyway.
      if (state.offset < 0 || st.size < state.offset || st.size - state.offset > lookBackBytes) rebuild(t, state);
      else if (st.size > state.offset) forward(t, state, st.size);
    } catch { return null; }
    const turn = state.turn;
    if (!turn || turn.by === OWN || turn.start === null) return null;
    return {
      tools: [...turn.tools.values()].map(tool => ({ ...tool })),
      tokens: [...turn.spent.values()].reduce((sum, n) => sum + n, 0),
      turnMs: Math.max(0, now() - turn.start),
      startedAt: turn.start,
    };
  }

  return { read };
}
